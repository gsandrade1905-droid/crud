        String rm;
        String nome;
        int idade;
        
        rm = jTextField1.getText();
        nome = jTextField2.getText();
        idade =Integer.parseInt( jTextField3.getText());
        
        String sql = "UPDATE tb_aluno set nm_aluno = ?, nr_idade = ? where rm_aluno = ?";
        
        try (Connection conn = conexao.conectar()) {
            PreparedStatement mensagem = conn.prepareStatement (sql);
            mensagem.setString(1, nome);
            mensagem.setString(2, String.valueOf(idade));
            mensagem.setString(3, rm);
            mensagem.executeUpdate();
            
        }catch(SQLException e) {
            throw new RuntimeException("Erro ao connectar", e);
        
    }               
